import { chromium } from '../.tools/browser-test/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('NetCafeServer/public/index.html','utf8');
for(const [,script] of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new Function(script);
const render=html.slice(html.indexOf('    function renderComputers('),html.indexOf('    let currentStartMode'));
const checkout=html.slice(html.indexOf('    async function openVipCheckoutModal('),html.indexOf('    async function confirmVipCheckout('));
assert.ok(checkout.length>100 && checkout.length<15000);
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage();
  await page.setContent('<div id="pcGrid"></div>');
  await page.addScriptTag({content:`let currentZoneFilter='ALL',pcSearchQuery='',isMainLayoutEdit=false,selectedPcIds=new Set();
    const computerState=()=>({online:true,color:'#10b981',label:'Band',detail:'Faol seans'});
    const formatTime=()=> '00:30:00';
    const escapeHtml=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
    ${render}`});
  await page.evaluate(()=>renderComputers([{id:'pc-test',name:'PC-7',status:'OCCUPIED',activeSession:{sessionId:'member',isMember:true,memberId:42,customerName:'gamer<img src=x>',memberBalance:46500,remainingSeconds:1800,paymentType:'BALANCE'}}]));
  assert.match(await page.locator('#pcGrid').innerText(),/Mijoz hisobi/);
  assert.match(await page.locator('#pcGrid').innerText(),/Hisob #42 balansi/);
  assert.equal(await page.locator('#pcGrid img').count(),0);
  assert.equal(await page.locator('[onclick*="requestStopSession"]').count(),1);
  const ids=[...checkout.matchAll(/getElementById\('([^']+)'\)/g)].map(m=>m[1]);
  await page.setContent([...new Set(ids)].map(id=>`<div id="${id}"></div>`).join(''));
  await page.addScriptTag({content:`let activeVipCheckoutData=null,selectedVipPayMethod='CASH';window.alert=message=>{throw Error(message)};${checkout}`});
  await page.evaluate(()=>openVipCheckoutModal('pc-test',{computerId:'pc-test',sessionId:'member',computerName:'PC-7',customerName:'gamer',playedMinutes:30,playedHours:0.5,gameBill:3500,barBill:10000,barItems:[],finalBill:13500,amountToCollect:10000,isMember:true,member:{accountId:42,username:'gamer',balance:43000,refundAmount:3500}}));
  assert.match(await page.locator('#checkoutMemberInfo').innerText(),/Hisobga qaytadi/);
  assert.equal((await page.locator('#vipCheckoutTotalBill').innerText()).replace(/\D/g,''),'10000','Cashier must collect bar only, not charge the game again');
  assert.equal(await page.locator('#checkoutMemberInfo').evaluate(el=>el.classList.contains('hidden')),false);
  const confirm=html.slice(html.indexOf('    async function confirmVipCheckout('),html.indexOf('    // --- TAB 2: TARIFFS'));
  await page.addScriptTag({content:`const messages=[];function showToast(message){messages.push(message)}function closeModal(){}function fetchData(){}const authToken='test';
    window.fetch=async()=>({ok:true,json:async()=>({amountCollected:10000,paymentMethod:'CASH',memberSummary:{username:'gamer',refundAmount:3500,balance:46500}})});
    ${confirm}`});
  await page.evaluate(()=>confirmVipCheckout());
  const messages=await page.evaluate(()=>messages);
  assert.match(messages[0].replace(/\s/g,''),/10000UZS/);
  assert.match(messages[1].replace(/\s/g,''),/46500/);
  console.log('PASS member PC identity, balance, close action, safe username and accurate cashier collection');
} finally {await browser.close();}
